#!/usr/bin/env python3
"""Prepare recorded ASR branch configuration and render minimal project context."""
from __future__ import annotations
import argparse
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re
import sys

SCRIPTS = Path.home() / ".codex/scripts"
sys.path.insert(0, str(SCRIPTS))
import asr360x_context as shared
from asr360x_context import (RepoInfo, Mapping, run_git, read_yl, gather, identity_hash,
                            repository_id, parse_project_map, product_family,
                            protocol_profile, memory_aliases, build_identity)
from asr360x_profile_store import prepare, atomic_write, store_root, PROFILE_PATH

PROJECT_MAP = shared.PROJECT_MAP
PROJECT_MAP_SOURCE = shared.PROJECT_MAP_SOURCE
GENERATED = "<!-- Generated by asr3601-project-onboard v2; project extensions belong in local.md. -->"


def match_mapping(info: RepoInfo) -> Mapping:
    return shared.match_mapping(info, PROJECT_MAP)


def build_command(info: RepoInfo) -> tuple[str, str]:
    try:
        result = prepare(info.root, write=False)
        return result["buildCommand"], "Confirmed branch record: " + result["recordPath"]
    except (ValueError, OSError, RuntimeError) as exc:
        return "未确认", str(exc)


def render_files(info: RepoInfo, config: dict | None = None) -> dict[str, str]:
    mapping = match_mapping(info)
    ctx = shared.context_from_info(info, mapping)
    if config is not None:
        command = config.get("buildCommand", "未确认")
        source = "Confirmed branch record: " + config["recordPath"] if config.get("recordPath") else config.get("error", "未确认")
    else:
        command, source = build_command(info)
    chip, os_name, ps = build_identity(command)
    product, priority = protocol_profile(info)
    agents = f"""# Codex Project Instructions
{GENERATED}

- Repository: `{info.name}`. Domain: ASR360x / Crane / LVGL firmware.
- Use live Git and source for current identity. `.codex-project/variant.md` is a generated view.
- Build parameters come from the confirmed branch record and `.codex-project/asr3602-build-profile.json`.
- After a branch switch, run in PowerShell: `python -X utf8 "$env:USERPROFILE/.codex/skills/asr3601-project-onboard/scripts/project_onboard.py" --repo . --prepare`.
- Build/release entrypoints prepare their own configuration. Reuse their result; do not add another full initialization.
- Formal release: `akq-firmware-release`. Normal build/flash: `asr3602-local-build-flash`. FOTA pair: `asr3602-fota-pair-release`.
- Bug list/detail: `zentao-bug-triage`. Current-branch fix: `asr3601-lvgl-firmware-triage`. Cross-branch port: `asr3601-cross-branch-porting`.
- Protocol evidence: `asr3601-protocol-branch-matrix`. CATStudio logs: `catstudio-log-extractor`.
- Preserve unrelated source changes and project-owned documents. Read `.codex-project/local.md` only when relevant; never overwrite it automatically.
- Record completed behavior fixes through `obsidian-fix-pattern-memory`; keep build evidence separate from device verification.
"""
    fields = [
        ("verified_at", datetime.now().astimezone().isoformat(timespec="seconds")),
        ("repo", str(info.root)), ("repo_id", ctx["repo_id"]),
        ("variant_id", ctx["variant_id"] or "未确认"), ("target_id", ctx["target_id"]),
        ("branch", info.branch), ("commit", info.commit),
        ("git_status_sha256", hashlib.sha256(("" if info.dirty == "干净" else info.dirty).encode()).hexdigest()),
        ("产品族", product_family(info)), ("客户/产品变体", info.branch),
        ("yl_device_name", info.yl_device_name), ("yl_device_ver", info.yl_device_ver),
        ("yl_hw_ver", info.yl_hw_ver), ("CHIP_ID", chip), ("TARGET_OS", os_name), ("PS_MODE", ps),
        ("构建目标", "craneg_modem_watch" if command != "未确认" else "未确认"),
        ("构建命令", command), ("构建来源", source), ("协议", product),
        ("禅道项目", ctx["project_name"]), ("禅道产品", ctx["product_name"]),
        ("project_id", ctx["project_id"] or "未确认"), ("product_id", ctx["product_id"] or "未确认"),
        ("映射状态", ctx["mapping_status"]), ("映射来源", PROJECT_MAP_SOURCE),
    ]
    variant = "# ASR Variant Fingerprint\n" + GENERATED + "\n\n"
    variant += "\n".join(f"- {key}：`{value}`" for key, value in fields)
    variant += f"\n- dirty worktree：\n\n```text\n{info.dirty}\n```\n\n"
    variant += "This is a generated view. Read live identity and registered build settings for execution. Protocol classification is a search hint, not implementation evidence.\n"
    return {"AGENTS.md": agents, ".codex-project/variant.md": variant}


def variant_fields(text: str) -> dict[str, str]:
    return {m.group(1).strip().strip("`"): m.group(2) for m in re.finditer(r"^-\s+([^：]+)：`([^`]*)`\s*$", text, re.M)}


def comparable_variant(text: str) -> str:
    return re.sub(r"^- verified_at：`[^`]*`\s*\n", "", text, count=1, flags=re.M).strip()


def task_snapshot_id(info: RepoInfo, files: dict[str, str]) -> str:
    fields = variant_fields(files[".codex-project/variant.md"])
    return identity_hash("|".join([repository_id(info), info.branch, info.commit, identity_hash(info.dirty, 12),
        info.yl_device_name, info.yl_device_ver, info.yl_hw_ver, fields.get("variant_id", ""), fields.get("target_id", "")]), 16)


def check_context(info: RepoInfo, files: dict[str, str]) -> int:
    path = info.root / ".codex-project/variant.md"
    current = path.read_text(encoding="utf-8-sig") if path.exists() else ""
    status = "current" if comparable_variant(current) == comparable_variant(files[".codex-project/variant.md"]) else "refreshable"
    print(f"status={status}\nbranch={info.branch}\nsnapshot_id={task_snapshot_id(info, files)}")
    return 0 if status == "current" else 2


def write_files(info: RepoInfo, files: dict[str, str], force: bool = False) -> list[str]:
    written = []
    for relative, content in files.items():
        path = info.root / relative
        if path.exists():
            old = path.read_text(encoding="utf-8-sig", errors="replace")
            if relative == "AGENTS.md":
                continue  # Even an appended note in a generated AGENTS is project-owned.
            if relative.endswith("variant.md") and comparable_variant(old) == comparable_variant(content):
                continue
        if atomic_write(path, content.encode("utf-8")):
            written.append(relative)
    return written


def resolve_git_dir(repo: Path) -> Path | None:
    value = run_git(repo, "rev-parse", "--git-common-dir")
    if value in {"不可用", "干净"}:
        return None
    path = Path(value)
    return (path if path.is_absolute() else repo / path).resolve()


def update_exclude(repo: Path) -> None:
    common = resolve_git_dir(repo)
    if not common:
        return
    path = common / "info/exclude"
    old = path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""
    additions = [line for line in ("AGENTS.md", ".codex-project/") if line not in old.splitlines()]
    if additions:
        atomic_write(path, (old.rstrip("\n") + "\n# Local Codex project context\n" + "\n".join(additions) + "\n").encode())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default=".")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--prepare", action="store_true", help="Restore the recorded configuration and render current context")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--force", action="store_true", help="Compatibility option; project-owned instructions are preserved")
    parser.add_argument("--no-exclude", action="store_true")
    args = parser.parse_args()
    repo = Path(args.repo).resolve()
    write = (args.write or args.prepare) and not (args.dry_run or args.check)
    if write and not args.no_exclude:
        update_exclude(repo)
    try:
        config = prepare(repo, write=write)
    except (ValueError, OSError, RuntimeError) as exc:
        config = {"status": "NEEDS_CONFIGURATION", "error": str(exc)}
    info = gather(repo)
    files = render_files(info, config)
    if args.check:
        return check_context(info, files)
    changed = write_files(info, files, args.force) if write else []
    result = shared.context_from_info(info, match_mapping(info))
    result.update({"configuration": config, "written": changed, "snapshot_id": task_snapshot_id(info, files)})
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    elif write:
        print(f"branch={info.branch}\nconfiguration={config['status']}\nwritten={','.join(changed) or 'none'}")
        if config.get("error"):
            print(config["error"])
    else:
        for relative, content in files.items():
            print(relative + "\n" + content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
